import fs from 'fs/promises';
import os from 'os';
import path from 'path';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import type { IStatsCache } from '@/types/stats';

let tempHome: string;

const SESSION_A = '4f2c9a10-1b2c-4d3e-8f90-0a1b2c3d4e5f';
const SESSION_B = '7a8b9c0d-1e2f-4a3b-8c4d-5e6f7a8b9c0d';
const CWD = '/work/claude-app';
const PROJECT_DIR = '-work-claude-app';
const OPUS = 'claude-opus-4-5-20251101';
const SONNET = 'claude-sonnet-4-5-20250929';

const jsonLine = (value: unknown): string => JSON.stringify(value);

const usage = (input: number, output: number, cacheRead: number, cache5m: number, cache1h: number) => ({
  input_tokens: input,
  output_tokens: output,
  cache_read_input_tokens: cacheRead,
  cache_creation_input_tokens: cache5m + cache1h,
  cache_creation: {
    ephemeral_5m_input_tokens: cache5m,
    ephemeral_1h_input_tokens: cache1h,
  },
});

const userPrompt = (sessionId: string, timestamp: string, text: string) => ({
  type: 'user',
  sessionId,
  cwd: CWD,
  timestamp,
  isSidechain: false,
  message: { role: 'user', content: text },
});

const toolResult = (sessionId: string, timestamp: string) => ({
  type: 'user',
  sessionId,
  cwd: CWD,
  timestamp,
  isSidechain: false,
  message: { role: 'user', content: [{ type: 'tool_result', tool_use_id: 'toolu_1', content: 'ok' }] },
});

const metaUser = (sessionId: string, timestamp: string) => ({
  type: 'user',
  sessionId,
  cwd: CWD,
  timestamp,
  isMeta: true,
  message: { role: 'user', content: 'Caveat: generated by a local command' },
});

const assistant = ({
  sessionId,
  timestamp,
  messageId,
  requestId,
  model,
  tokens,
  content = [{ type: 'text', text: 'done' }],
}: {
  sessionId: string;
  timestamp: string;
  messageId?: string;
  requestId?: string;
  model: string;
  tokens: ReturnType<typeof usage>;
  content?: unknown[];
}) => ({
  type: 'assistant',
  sessionId,
  cwd: CWD,
  timestamp,
  requestId,
  message: { id: messageId, model, role: 'assistant', content, usage: tokens },
});

// One API response written as three lines (thinking, text, tool_use) with identical usage.
const splitResponse = (sessionId: string, date: string) => [
  assistant({
    sessionId,
    timestamp: `${date}T02:00:01.000Z`,
    messageId: 'msg_A',
    requestId: 'req_A',
    model: OPUS,
    tokens: usage(10, 20, 1000, 100, 200),
    content: [{ type: 'thinking', thinking: '' }],
  }),
  assistant({
    sessionId,
    timestamp: `${date}T02:00:02.000Z`,
    messageId: 'msg_A',
    requestId: 'req_A',
    model: OPUS,
    tokens: usage(10, 20, 1000, 100, 200),
    content: [{ type: 'text', text: 'Looking' }],
  }),
  assistant({
    sessionId,
    timestamp: `${date}T02:00:03.000Z`,
    messageId: 'msg_A',
    requestId: 'req_A',
    model: OPUS,
    tokens: usage(10, 20, 1000, 100, 200),
    content: [{ type: 'tool_use', id: 'toolu_1', name: 'Read', input: {} }],
  }),
];

const writeTranscript = async (name: string, lines: unknown[], dir = PROJECT_DIR): Promise<string> => {
  const projectDir = path.join(tempHome, '.claude', 'projects', dir);
  await fs.mkdir(projectDir, { recursive: true });
  const filePath = path.join(projectDir, name);
  await fs.writeFile(filePath, lines.map(jsonLine).join('\n'), 'utf-8');
  return filePath;
};

const readCacheFile = async (): Promise<{ version: number; days: Record<string, Record<string, unknown>> }> => {
  const { getDataDir } = await import('@/lib/app-identity');
  const content = await fs.readFile(path.join(getDataDir(), 'stats', 'cache.json'), 'utf-8');
  return JSON.parse(content);
};

const writeV4Cache = async (days: Record<string, unknown>, lastComputedDate: string): Promise<void> => {
  const { getDataDir } = await import('@/lib/app-identity');
  const dir = path.join(getDataDir(), 'stats');
  await fs.mkdir(dir, { recursive: true });
  await fs.writeFile(
    path.join(dir, 'cache.json'),
    JSON.stringify({ version: 4, lastComputedDate, days }),
    'utf-8',
  );
};

const codexDay = (messageCount: number, input: number, sessionId: string, date: string) => ({
  messageCount,
  sessionCount: 1,
  toolCallCount: 2,
  hourCounts: { '9': messageCount },
  modelTokens: {
    'gpt-5.5': { input, output: 50, cacheRead: 0, cacheCreation: 0, cacheCreation5m: 0, cacheCreation1h: 0 },
  },
  sessions: [{ id: sessionId, start: `${date}T09:00:00.000Z`, end: `${date}T09:30:00.000Z`, messages: messageCount }],
});

describe('Claude Code stats parsing', () => {
  beforeEach(async () => {
    tempHome = await fs.mkdtemp(path.join(os.tmpdir(), 'agentmux-stats-claude-'));
    vi.resetModules();
    vi.stubEnv('HOME', tempHome);
    vi.stubEnv('USERPROFILE', tempHome);
    vi.stubEnv('AGENTMUX_DATA_DIR', '');
    vi.stubEnv('CODEXMUX_DATA_DIR', '');
    vi.useFakeTimers();
    vi.setSystemTime(new Date('2026-04-28T12:00:00.000Z'));
  });

  afterEach(async () => {
    vi.useRealTimers();
    vi.unstubAllEnvs();
    await fs.rm(tempHome, { recursive: true, force: true });
  });

  it('counts an assistant response split over three lines once', async () => {
    await writeTranscript(`${SESSION_A}.jsonl`, [
      userPrompt(SESSION_A, '2026-04-27T02:00:00.000Z', 'Fix the build'),
      ...splitResponse(SESSION_A, '2026-04-27'),
    ]);

    const { getStatsCache } = await import('@/lib/stats/stats-cache');
    const { parseAllSessions } = await import('@/lib/stats/jsonl-parser');

    const cache = await getStatsCache();
    expect(cache.modelUsage[OPUS]).toMatchObject({
      inputTokens: 10,
      outputTokens: 20,
      cacheReadInputTokens: 1000,
      cacheCreationInputTokens: 300,
    });
    expect(cache.dailyActivity).toContainEqual({
      date: '2026-04-27',
      messageCount: 1,
      sessionCount: 1,
      toolCallCount: 1,
    });

    const sessions = await parseAllSessions('all');
    expect(sessions).toHaveLength(1);
    expect(sessions[0].totalTokens).toBe(10 + 20 + 1000 + 300);
  });

  it('counts a message id shared by two transcripts once', async () => {
    await writeTranscript(`${SESSION_A}.jsonl`, [
      userPrompt(SESSION_A, '2026-04-27T02:00:00.000Z', 'Fix the build'),
      ...splitResponse(SESSION_A, '2026-04-27'),
    ]);
    await writeTranscript(`${SESSION_B}.jsonl`, [
      ...splitResponse(SESSION_B, '2026-04-27'),
      userPrompt(SESSION_B, '2026-04-27T03:00:00.000Z', 'Continue after fork'),
      assistant({
        sessionId: SESSION_B,
        timestamp: '2026-04-27T03:00:05.000Z',
        messageId: 'msg_C',
        requestId: 'req_C',
        model: OPUS,
        tokens: usage(1, 2, 3, 4, 0),
      }),
    ]);

    const { getStatsCache } = await import('@/lib/stats/stats-cache');
    const { parseAllSessions } = await import('@/lib/stats/jsonl-parser');

    const cache = await getStatsCache();
    expect(cache.modelUsage[OPUS]).toMatchObject({
      inputTokens: 11,
      outputTokens: 22,
      cacheReadInputTokens: 1003,
      cacheCreationInputTokens: 304,
      cacheCreation5mInputTokens: 104,
      cacheCreation1hInputTokens: 200,
    });

    const sessions = await parseAllSessions('all');
    expect(sessions).toHaveLength(2);
    expect(sessions.reduce((sum, s) => sum + s.totalTokens, 0)).toBe(1330 + 10);
  });

  it('counts only real user prompts as messages', async () => {
    await writeTranscript(`${SESSION_A}.jsonl`, [
      userPrompt(SESSION_A, '2026-04-27T02:00:00.000Z', 'Fix the build'),
      ...splitResponse(SESSION_A, '2026-04-27'),
      toolResult(SESSION_A, '2026-04-27T02:00:04.000Z'),
      metaUser(SESSION_A, '2026-04-27T02:00:05.000Z'),
      toolResult(SESSION_A, '2026-04-27T02:00:06.000Z'),
      userPrompt(SESSION_A, '2026-04-27T02:10:00.000Z', 'Now add a test'),
    ]);

    const { getStatsCache } = await import('@/lib/stats/stats-cache');
    const { parseAllSessions } = await import('@/lib/stats/jsonl-parser');
    const { parseHistory } = await import('@/lib/stats/history-parser');

    const cache = await getStatsCache();
    expect(cache.totalMessages).toBe(2);
    expect(Object.values(cache.hourCounts).reduce((sum, count) => sum + count, 0)).toBe(2);

    const sessions = await parseAllSessions('all');
    expect(sessions[0].messageCount).toBe(2);

    const history = await parseHistory('all');
    expect(history.totalEntries).toBe(2);
  });

  it('keeps per-model totals and splits cache creation into 5m and 1h', async () => {
    await writeTranscript(`${SESSION_A}.jsonl`, [
      userPrompt(SESSION_A, '2026-04-27T02:00:00.000Z', 'Fix the build'),
      ...splitResponse(SESSION_A, '2026-04-27'),
      assistant({
        sessionId: SESSION_A,
        timestamp: '2026-04-27T02:01:00.000Z',
        messageId: 'msg_B',
        requestId: 'req_B',
        model: SONNET,
        tokens: usage(5, 7, 0, 40, 0),
      }),
      assistant({
        sessionId: SESSION_A,
        timestamp: '2026-04-27T02:02:00.000Z',
        messageId: 'msg_synthetic',
        model: '<synthetic>',
        tokens: usage(0, 0, 0, 0, 0),
      }),
    ]);

    const { getStatsCache } = await import('@/lib/stats/stats-cache');
    const cache = await getStatsCache();

    expect(Object.keys(cache.modelUsage).sort()).toEqual([OPUS, SONNET]);
    expect(cache.modelUsage[OPUS]).toMatchObject({
      inputTokens: 10,
      outputTokens: 20,
      cacheReadInputTokens: 1000,
      cacheCreationInputTokens: 300,
      cacheCreation5mInputTokens: 100,
      cacheCreation1hInputTokens: 200,
    });
    expect(cache.modelUsage[SONNET]).toMatchObject({
      inputTokens: 5,
      outputTokens: 7,
      cacheReadInputTokens: 0,
      cacheCreationInputTokens: 40,
      cacheCreation5mInputTokens: 40,
      cacheCreation1hInputTokens: 0,
    });
  });

  it('marks Claude session stats with the claude provider', async () => {
    await writeTranscript(`${SESSION_A}.jsonl`, [
      userPrompt(SESSION_A, '2026-04-27T02:00:00.000Z', 'Fix the build'),
      ...splitResponse(SESSION_A, '2026-04-27'),
      assistant({
        sessionId: SESSION_A,
        timestamp: '2026-04-27T02:02:00.000Z',
        messageId: 'msg_synthetic',
        model: '<synthetic>',
        tokens: usage(0, 0, 0, 0, 0),
      }),
    ]);

    const { parseAllSessions } = await import('@/lib/stats/jsonl-parser');
    const sessions = await parseAllSessions('all');

    expect(sessions).toEqual([
      {
        sessionId: SESSION_A,
        provider: 'claude',
        project: CWD,
        startedAt: '2026-04-27T02:00:00.000Z',
        lastActivityAt: '2026-04-27T02:02:00.000Z',
        messageCount: 1,
        totalTokens: 1330,
        model: OPUS,
      },
    ]);
  });

  it('migrates a v4 cache, keeping days without source files and adding Claude usage', async () => {
    const oldDay = codexDay(7, 500, 'codex-old', '2026-04-20');
    const cachedDay = codexDay(3, 100, 'codex-26', '2026-04-26');
    await writeV4Cache({ '2026-04-20': oldDay, '2026-04-26': cachedDay }, '2026-04-27');
    await writeTranscript(`${SESSION_A}.jsonl`, [
      userPrompt(SESSION_A, '2026-04-26T02:00:00.000Z', 'Fix the build'),
      ...splitResponse(SESSION_A, '2026-04-26'),
      userPrompt(SESSION_A, '2026-04-26T02:10:00.000Z', 'Now add a test'),
    ]);

    const { getStatsCache } = await import('@/lib/stats/stats-cache');
    const stats = await getStatsCache();
    const file = await readCacheFile();

    expect(file.version).toBe(5);
    expect(file.days['2026-04-20']).toEqual(oldDay);
    expect(file.days['2026-04-26']).toMatchObject({
      messageCount: 5,
      sessionCount: 2,
      toolCallCount: 3,
      modelTokens: {
        'gpt-5.5': cachedDay.modelTokens['gpt-5.5'],
        [OPUS]: {
          input: 10,
          output: 20,
          cacheRead: 1000,
          cacheCreation: 300,
          cacheCreation5m: 100,
          cacheCreation1h: 200,
        },
      },
    });
    expect(stats.totalMessages).toBe(7 + 5);
    expect(stats.dailyActivity).toContainEqual({
      date: '2026-04-20',
      messageCount: 7,
      sessionCount: 1,
      toolCallCount: 2,
    });
  });

  it('migrates a v4 cache without recomputing when there is no Claude transcript', async () => {
    const oldDay = codexDay(7, 500, 'codex-old', '2026-04-20');
    await writeV4Cache({ '2026-04-20': oldDay }, '2026-04-27');

    const { getStatsCache } = await import('@/lib/stats/stats-cache');
    const stats = await getStatsCache();
    const file = await readCacheFile();

    expect(file.version).toBe(5);
    expect(file.days).toEqual({ '2026-04-20': oldDay });
    expect(stats.totalMessages).toBe(7);
  });

  it('leaves Claude model cost unestimated and out of the totals', async () => {
    const { buildOverview } = await import('@/lib/stats/stats-cache-parser');
    const tokens = { input: 1_000_000, output: 1_000_000, cacheRead: 1_000_000, cacheCreation: 0, cacheCreation5m: 0, cacheCreation1h: 0 };
    const modelUsage = (input: number) => ({
      inputTokens: input,
      outputTokens: 1_000_000,
      cacheReadInputTokens: 1_000_000,
      cacheCreationInputTokens: 0,
      cacheCreation5mInputTokens: 0,
      cacheCreation1hInputTokens: 0,
      webSearchRequests: 0,
      costUSD: 0,
      contextWindow: 0,
      maxOutputTokens: 0,
    });
    const cache: IStatsCache = {
      version: 5,
      lastComputedDate: '2026-04-28',
      dailyActivity: [{ date: '2026-04-28', messageCount: 2, sessionCount: 2, toolCallCount: 0 }],
      dailyModelTokens: [{ date: '2026-04-28', tokensByModel: { 'gpt-5.5': tokens, [OPUS]: tokens } }],
      modelUsage: { 'gpt-5.5': modelUsage(1_000_000), [OPUS]: modelUsage(1_000_000) },
      totalSessions: 2,
      totalMessages: 2,
      longestSession: { sessionId: '', duration: 0, messageCount: 0, timestamp: '' },
      firstSessionDate: '2026-04-28',
      hourCounts: {},
      dayHourCounts: {},
      totalSpeculationTimeSavedMs: 0,
    };

    for (const period of ['all', '7d'] as const) {
      const overview = buildOverview(cache, period);
      expect(overview.modelTokens[OPUS].cost).toBeNull();
      expect(overview.modelTokens['gpt-5.5'].cost).toBeCloseTo(35.5);
      expect(overview.totalCost).toBeCloseTo(35.5);
    }
    expect(buildOverview(cache, 'all').todayCost).toBeCloseTo(35.5);
  });
});
